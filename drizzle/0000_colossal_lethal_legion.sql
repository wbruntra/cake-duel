CREATE TABLE `games` (
	`id` text PRIMARY KEY NOT NULL,
	`status` text DEFAULT 'waiting' NOT NULL,
	`player1_id` text NOT NULL,
	`player2_id` text,
	`current_bout` integer DEFAULT 1 NOT NULL,
	`bout1_winner` text,
	`bout2_winner` text,
	`bout3_winner` text,
	`winner` text,
	`turn_player` text,
	`turn_phase` text,
	`p1_hand` text DEFAULT '[]' NOT NULL,
	`p2_hand` text DEFAULT '[]' NOT NULL,
	`p1_cakes` integer DEFAULT 3 NOT NULL,
	`p2_cakes` integer DEFAULT 4 NOT NULL,
	`p1_handsize` integer DEFAULT 4 NOT NULL,
	`p2_handsize` integer DEFAULT 4 NOT NULL,
	`deck` text DEFAULT '[]' NOT NULL,
	`discard` text DEFAULT '[]' NOT NULL,
	`attack_claim` text,
	`attack_count` integer,
	`block_claim` text,
	`block_count` integer,
	`attack_cards` text,
	`block_cards` text,
	`passed_last` text,
	`bout_end_acks` text DEFAULT '[]' NOT NULL,
	`created_at` text NOT NULL
);
