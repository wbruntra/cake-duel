import { sqliteTable, text, integer } from "drizzle-orm/sqlite-core";

export const games = sqliteTable("games", {
  id: text("id").primaryKey(),
  status: text("status", { enum: ["waiting", "playing", "finished"] }).notNull().default("waiting"),
  player1Id: text("player1_id").notNull(),
  player2Id: text("player2_id"),
  currentBout: integer("current_bout").notNull().default(1),
  bout1Winner: text("bout1_winner"),
  bout2Winner: text("bout2_winner"),
  bout3Winner: text("bout3_winner"),
  winner: text("winner"),
  turnPlayer: text("turn_player"),
  turnPhase: text("turn_phase", { enum: ["attack", "block", "resolve", "resupply", "bout_end"] }),
  p1Hand: text("p1_hand").notNull().default("[]"),
  p2Hand: text("p2_hand").notNull().default("[]"),
  p1Cakes: integer("p1_cakes").notNull().default(3),
  p2Cakes: integer("p2_cakes").notNull().default(4),
  p1HandSize: integer("p1_handsize").notNull().default(4),
  p2HandSize: integer("p2_handsize").notNull().default(4),
  deck: text("deck").notNull().default("[]"),
  discard: text("discard").notNull().default("[]"),
  attackClaim: text("attack_claim"),
  attackCount: integer("attack_count"),
  blockClaim: text("block_claim"),
  blockCount: integer("block_count"),
  attackCards: text("attack_cards"),
  blockCards: text("block_cards"),
  passedLast: integer("passed_last"),
  createdAt: text("created_at").notNull(),
});
